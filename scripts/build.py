def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def resolve_libs(libs):
    needed = set()

    def add(name):
        if name in needed:
            return
        for dep in LIB_DEPS[name]:
            add(dep)
        needed.add(name)

    for lib in libs:
        add(lib)
    return [name for name in LIB_ORDER if name in needed]


def assets():
    checklists = {p.stem: p.read_text(encoding="utf-8").strip() for p in sorted((ROOT / "prompts/checklists").glob("*.md"))}
    return {
        "system": read("prompts/system.md").strip(),
        "checklists": checklists,
        "schema": json.loads(read("prompts/review.schema.json")),
    }


def js_code(snippet, libs=(), config=None, with_assets=False):
    body = read(f"n8n/code/nodes/{snippet}.js")
    head = ["// Generated by scripts/build.py from n8n/code/. Prefer editing the sources and rebuilding."]
    if "const CONFIG = __CONFIG__;" in body:
        body = body.replace("const CONFIG = __CONFIG__;\n", "")
        head.append("// ===== secrev settings (edit here) =====\nconst CONFIG = " + json.dumps(config, indent=2) +
                    ";\n// =======================================")
    parts = head
    if with_assets:
        parts.append("const SECREV_ASSETS = " + json.dumps(assets(), ensure_ascii=False) + ";")
    parts += [read(f"n8n/code/lib/{name}.js").strip() for name in resolve_libs(libs)]
    parts.append(body.strip())
    return "\n\n".join(parts) + "\n"


class Workflow:
    def __init__(self, key, name):
        self.key, self.name = key, name
        self.nodes, self.connections = [], {}

    def add(self, name, type_, version, params, pos, **settings):
        node = {"parameters": params, "id": str(uuid.uuid5(NODE_NS, f"{self.key}/{name}")), "name": name,
                "type": type_, "typeVersion": version, "position": list(pos)}
        node.update(settings)
        self.nodes.append(node)
        return name

    def link(self, src, dst, output=0, input_=0):
        outs = self.connections.setdefault(src, {}).setdefault("main", [])
        while len(outs) <= output:
            outs.append([])
        outs[output].append({"node": dst, "type": "main", "index": input_})

    def chain(self, *names):
        for a, b in zip(names, names[1:]):
            self.link(a, b)

    def to_json(self, extra_settings=None):
        return {
            "id": WORKFLOW_IDS[self.key], "name": self.name, "nodes": self.nodes, "connections": self.connections,
            "settings": {**SETTINGS, **(extra_settings or {})}, "active": False, "pinData": {},
            "meta": {"templateCredsSetupCompleted": True}, "tags": [],
        }

    # --- node helpers
    def code(self, name, pos, snippet, libs=(), config=None, with_assets=False, **settings):
        return self.add(name, "n8n-nodes-base.code", 2,
                        {"jsCode": js_code(snippet, libs, config, with_assets)}, pos, **settings)

    def http(self, name, pos, url, method="GET", headers=None, json_body=None, response=None, pagination=None,
             timeout=30000, credential=None, sequential=False, **settings):
        params = {"method": method, "url": url}
        if credential:
            params.update({"authentication": "genericCredentialType", "genericAuthType": credential})
        if headers:
            params.update({"sendHeaders": True, "headerParameters": {"parameters": headers}})
        if json_body is not None:
            params.update({"sendBody": True, "specifyBody": "json", "jsonBody": json_body})
        options = {"timeout": timeout}
        if response:
            options["response"] = {"response": response}
        if pagination:
            options["pagination"] = {"pagination": pagination}
        if sequential:  # the node otherwise sends all items' requests concurrently
            options["batching"] = {"batch": {"batchSize": 1, "batchInterval": 0}}
        params["options"] = options
        if credential:
            settings["credentials"] = {credential: CREDS[credential]}
        return self.add(name, "n8n-nodes-base.httpRequest", 4.2, params, pos, **settings)

    def condition(self, name, pos, expr):
        cond = {"id": str(uuid.uuid5(NODE_NS, f"{self.key}/{name}/cond")), "leftValue": expr, "rightValue": "",
                "operator": {"type": "boolean", "operation": "true", "singleValue": True}}
        return self.add(name, "n8n-nodes-base.if", 2.2, {
            "conditions": {"options": {"caseSensitive": True, "leftValue": "", "typeValidation": "loose", "version": 2},
                           "conditions": [cond], "combinator": "and"},
            "options": {}}, pos)

    def call(self, name, pos, target, wait, **settings):
        return self.add(name, "n8n-nodes-base.executeWorkflow", 1.2, {
            "workflowId": {"__rl": True, "value": WORKFLOW_IDS[target], "mode": "id"},
            "options": {"waitForSubWorkflow": wait}}, pos, **settings)


def gh_headers(accept="application/vnd.github+json"):
    return [
        {"name": "Authorization", "value": "={{ 'Bearer ' + $('Get GitHub token').first().json.token }}"},
        {"name": "Accept", "value": accept},
        {"name": "X-GitHub-Api-Version", "value": "2022-11-28"},
    ]


def gh_pages(max_pages, field=None):
    size = f"($response.body.{field} || [])" if field else "$response.body"
    return {"paginationMode": "updateAParameterInEachRequest",
            "parameters": {"parameters": [{"type": "qs", "name": "page", "value": "={{ $pageCount + 1 }}"}]},
            "paginationCompleteWhen": "other", "completeExpression": f"={{{{ {size}.length < 100 }}}}",
            "limitPagesFetched": True, "maxRequests": max_pages}


def pick(cfg, key):
    return {k: cfg[k] for k in CONFIG_KEYS[key]}


# --------------------------------------------------------------------------- workflows
def intake(cfg):
    wf = Workflow("intake", "secrev-intake")
    wf.add("GitHub webhook", "n8n-nodes-base.webhook", 2.1,
           {"httpMethod": "POST", "path": cfg["webhook_path"], "responseMode": "onReceived", "options": {"rawBody": True}},
           (0, 300), webhookId=str(uuid.uuid5(NODE_NS, "intake/webhook")))
    wf.add("Compute signature", "n8n-nodes-base.crypto", 2,
           {"action": "hmac", "binaryData": True, "binaryPropertyName": "data", "type": "SHA256",
            "dataPropertyName": "secrev_signature", "encoding": "hex"},
           (220, 300), credentials={"crypto": CREDS["crypto"]})
    wf.code("Route event", (440, 300), "intake-route", ["util"], pick(cfg, "intake"))
    wf.add("Let the PR settle", "n8n-nodes-base.wait", 1.1, {"amount": cfg["settle_seconds"], "unit": "seconds"},
           (660, 300), webhookId=str(uuid.uuid5(NODE_NS, "intake/wait")))
    wf.call("Start review", (880, 300), "review", wait=False)
    wf.chain("GitHub webhook", "Compute signature", "Route event", "Let the PR settle", "Start review")
    return wf.to_json({"executionTimeout": 300})


def token(cfg):
    wf = Workflow("token", "secrev-github-token")
    wf.add("Start", "n8n-nodes-base.executeWorkflowTrigger", 1.1, {"inputSource": "passthrough"}, (0, 300))
    wf.code("Build JWT claims", (220, 300), "token-claims", [], pick(cfg, "token"))
    wf.add("Sign app JWT", "n8n-nodes-base.jwt", 1,
           {"operation": "sign", "useJson": True, "claimsJson": "={{ JSON.stringify($json.claims) }}",
            "options": {"algorithm": "RS256"}},
           (440, 300), credentials={"jwtAuth": CREDS["jwtAuth"]})
    api = cfg["github_api_url"]
    wf.http("Create installation token", (660, 300),
            f"={api}/app/installations/{{{{ $('Build JWT claims').first().json.installation_id }}}}/access_tokens",
            method="POST",
            headers=[{"name": "Authorization", "value": "={{ 'Bearer ' + $json.token }}"},
                     {"name": "Accept", "value": "application/vnd.github+json"},
                     {"name": "X-GitHub-Api-Version", "value": "2022-11-28"}],
            json_body="={{ JSON.stringify($('Build JWT claims').first().json.request) }}",
            retryOnFail=True, maxTries=3, waitBetweenTries=2000)
    wf.code("Return token", (880, 300), "token-result", [], pick(cfg, "token"))
    wf.chain("Start", "Build JWT claims", "Sign app JWT", "Create installation token", "Return token")
    return wf.to_json({"executionTimeout": 120})


