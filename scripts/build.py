def scan_workflow():
    embedded = []
    for name in ["run-scanners.sh", "bundle.py", "versions.env", "gitleaks.toml", "ansible-lint.yml"]:
        content = read(f"scanners/{name}")
        if "${{" in content or "SECREV_EOF" in content:
            sys.exit(f"scanners/{name} must not contain '${{{{' or 'SECREV_EOF'")
        embedded.append(f"cat > \"$RUNNER_TEMP/secrev/{name}\" <<'SECREV_EOF'")
        embedded += content.rstrip("\n").split("\n")
        embedded.append("SECREV_EOF")
    block = "\n".join(("          " + line) if line else "" for line in embedded)
    return read("scanners/scan.template.yml").replace("__EMBEDDED_FILES__", block)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="n8n/config.json")
    ap.add_argument("--out", default="n8n/workflows")
    ap.add_argument("--check", action="store_true", help="exit 1 if generated files differ from what is on disk")
    ap.add_argument("--workflows-only", action="store_true", help="only build the n8n workflows (used by e2e tests)")
    args = ap.parse_args()
    cfg = json.loads(read(args.config) if not Path(args.config).is_absolute() else Path(args.config).read_text())
    out = Path(args.out) if Path(args.out).is_absolute() else ROOT / args.out
    outputs = {} if args.workflows_only else {ROOT / ".github/workflows/scan.yml": scan_workflow()}
    outputs |= {
        out / "secrev-intake.json": json.dumps(intake(cfg), indent=2) + "\n",
        out / "secrev-github-token.json": json.dumps(token(cfg), indent=2) + "\n",
        out / "secrev-review-pr.json": json.dumps(review(cfg), indent=2) + "\n",
        out / "secrev-sweeper.json": json.dumps(sweeper(cfg), indent=2) + "\n",
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    if stale:
        print("stale generated files (run python3 scripts/build.py):", *[str(p) for p in stale], sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
